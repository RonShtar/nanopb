local function gen_c()
    local title = "Generate C (merged + validation)"
    ask_dirs(title, true, nil, function()
        pick_units(title, function(units)
            -- Port-mapped messages are the protocol entrypoints that get a packet filter.
            local args = add_common({ "gen", "--out", output_dir(), "--unit", units })
            if (config.include_prefix or "") ~= "" then
                args[#args + 1] = "--include-prefix"
                args[#args + 1] = config.include_prefix
            end
            if (config.author or "") ~= "" then
                args[#args + 1] = "--author"
                args[#args + 1] = config.author
            end
            if config.port_map ~= "" then
                args[#args + 1] = "--port-map"
                args[#args + 1] = config.port_map
            end
            local ok, text = run_backend(args)
            if not ok then return false, text end
            return true, (json_string(text, "summary") or text) .. "\n\n" ..
                "<unit>.pb.c/.h: all messages, PB_BINDs and the packet filters (_udp/_tcp).\n" ..
                "<unit>_validate.c/.h: all pb_validate_* validators.\n" ..
                "Add all four to your project, next to the nanopb runtime.\n" ..
                "Each protocol is self-contained: imports from outside its folder\n" ..
                "(google/protobuf/*, shared protos) carry its prefix (camera_google_protobuf_Any),\n" ..
                "so any protocols link together. Filter: <protocol>_udp / <protocol>_tcp.\n" ..
                "Compile the nanopb runtime once (common/ when generated together).\n" ..
                "The -D values are optional: they shrink the validation buffers to what this\n" ..
                "schema needs (docs/validation_performance.md)."
        end)
    end)
end

local DROPPED_FILTER = 'nanopb.validation == "dropped"'
local PASSED_FILTER = 'nanopb.validation == "passed"'

-- One button: valid and invalid packets of every message in one capture,
-- dissector refreshed, capture opened. Every packet is a google.protobuf.Any
-- (type_url = message) on its protocol's port, mapped like a Decode As to
-- the <protocol> dissector; each one is also written as a C array (.h) and .hex.
local function gen_packets()
    local title = "Generate test packets"
    ask_dirs(title, true, nil, function()
        pick_units(title, function(units)
            local args = add_common({ "packets", "--mode", "protocol", "--out", output_dir(),
                "--unit", units, "--plugins-dir", PLUGINS_DIR, "--drop-stale-ports" })
            if config.port_map ~= "" then
                args[#args + 1] = "--port-map"
                args[#args + 1] = config.port_map
            end
            local ok, text = run_backend(args)
            if not ok then return false, text end
            local pcap = json_string(text, "pcap") or ""
            local summary = json_string(text, "summary") or text
            local picked = json_string(text, "port_map") or ""
            if (config.port_map == "" and picked ~= "") or json_bool(text, "ports_pruned") then
                -- Keep the ports gen-packets picked, so the dissector and Generate C agree.
                config.port_map = picked
                save_config()
            end
            local reload = json_bool(text, "schema_changed") and reload_lua_plugins
            local notes = { summary, "" }
            if open_capture_file then
                notes[#notes + 1] = "Press Open capture to see it. Each packet shows Validation: PASSED or DROPPED."
                notes[#notes + 1] = "Other ports: Analyze > Decode As > UDP/TCP port > FLEET (your folder name), or set it for all NANOPB"
                    .. "\ntraffic: Edit > Preferences > Protocols > NANOPB > Protocol."
            else
                notes[#notes + 1] = "Open the capture with File > Open: " .. pcap
            end
            if json_bool(text, "schema_changed") then
                notes[#notes + 1] = reload_lua_plugins and "The protocols changed; Open capture also reloads Lua plugins, which closes this window."
                    or "The dissector schema changed; reload Lua plugins (Ctrl+Shift+L)."
            end
            local function open_capture()
                if open_capture_file and pcap ~= "" then open_capture_file(pcap, "") end
                -- Last: reloading re-runs the plugins and re-dissects the open capture.
                if reload then reload_lua_plugins() end
            end
            local function show_only(filter)
                return function()
                    set_filter(filter)
                    apply_filter()
                end
            end
            -- The window stays in front until a button is pressed: opening the capture
            -- by itself would bring the main window up and hide this one.
            local buttons = {}
            if open_capture_file then buttons[#buttons + 1] = { "Open capture", open_capture } end
            if set_filter and apply_filter then
                buttons[#buttons + 1] = { "Show passed only", show_only(PASSED_FILTER) }
                buttons[#buttons + 1] = { "Show dropped only", show_only(DROPPED_FILTER) }
                buttons[#buttons + 1] = { "Show all", show_only("") }
            end
            local packets = units:find(",", 1, true) and output_dir()
                or (output_dir() .. SEP .. units .. SEP .. "packets")
            buttons[#buttons + 1] = { "Open packets folder", function() open_folder(packets) end }
            return true, table.concat(notes, "\n"), buttons
        end)
    end)
end

-- Only the protos directory: every subdirectory with .proto files becomes a
-- protocol (FLEET, SHARED, ...) of the dissector; the port map is kept.
local function load_now(title, note)
    local args = add_common({ "wireshark", "load", "--plugins-dir", PLUGINS_DIR, "--drop-stale-ports" })
    if config.port_map ~= "" then
        args[#args + 1] = "--port-map"
        args[#args + 1] = config.port_map
    end
    local ok, text = run_backend(args)
    if ok then
        if json_bool(text, "ports_pruned") then
            config.port_map = json_string(text, "port_map") or ""
            save_config()
        end
        text = (json_string(text, "summary") or text) .. (note or "")
        if reload_lua_plugins then
            -- Reloading closes every plugin window, so it waits until this one has been read.
            show(title, ok, text .. "\n\nPress Activate to reload Lua plugins and use these protocols.",
                nil, { { "Activate", reload_lua_plugins } })
            return
        end
        text = text .. "\n\nReload Lua plugins (Analyze > Reload Lua Plugins, Ctrl+Shift+L) to activate."
    end
    show(title, ok, text)
end

-- Enter the directory one time: it is loaded now, and the other menu items
-- use it without asking until it is set again here.
local function set_directory()
    local title = "Set protos directory"
    dialog(title, {
        { "Protos directory (the folder with one subfolder per protocol)", config.protos_root },
        { "Output directory (empty = <protos directory>/../nanopb_out)", config.output_dir },
        { "Include nanopb headers from (e.g. NanoPB for <NanoPB/pb.h>; empty = <pb.h>)", config.include_prefix },
        { "@author in generated files (empty = Generated by nanopb validate)", config.author },
    }, function(input, output, prefix, author)
        input = trim(input)
        if input == "" then
            show(title, false, "Enter the protos directory.")
            return
        end
        config.protos_root = input
        config.output_dir = trim(output)
        config.include_prefix = trim(prefix or "")
        config.author = trim(author or "")
        config.protos_root_fixed = "1"
        save_config()
        load_now(title, "\n\nEvery Tools > nanopb item now uses this directory without asking."
            .. "\nTo change it, run Set protos directory (once) again.")
    end)
end

local function about()
    show("nanopb studio", true, table.concat({
        "Plugins folder: " .. PLUGINS_DIR,
        "State file: " .. CONFIG_PATH,
