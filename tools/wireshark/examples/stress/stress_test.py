#!/usr/bin/env python3
"""End-to-end stress test for the nanopb Wireshark tools.

Uses examples/stress/protos: one unit ("fleet", 6 protos, proto2 + proto3)
that also pulls in shared/units.proto, google/protobuf/any.proto and
google/protobuf/timestamp.proto. Covers nested messages and enums, oneof,
map, packed and unpacked repeated fields, every scalar type, Timestamp,
several Any fields (one holding a Batch of Any, recursively), proto2
required/defaults, a project-provided any.options and validation rules.

Steps:
  1. gen-c     -> <out>/fleet/fleet.c + fleet.h (+ nanopb runtime)
  2. gen-data  -> <out>/fleet/data/* for every message
  3. C round trip: compile fleet.c with strict warnings, then decode,
     validate and re-encode every sample in C
  4. Packets: hand-made showcase packets + every sample -> <out>/stress.pcap
  5. tshark: dissect the capture and check every packet
  6. --install: put the stress schema into your Wireshark plugins folder

  python tools/wireshark/examples/stress/stress_test.py [--install]
"""

from __future__ import print_function

import argparse
import os
import re
import shutil
import subprocess
import sys

STRESS_DIR = os.path.dirname(os.path.abspath(__file__))
TOOL_DIR = os.path.dirname(os.path.dirname(STRESS_DIR))
sys.path.insert(0, os.path.join(TOOL_DIR, 'tests'))
sys.path.insert(0, os.path.join(TOOL_DIR, 'tests', 'live'))

from helpers import REPO_ROOT, run_backend, varint  # noqa: E402
from cases import Case  # noqa: E402
import live_test  # noqa: E402
import nanopb_wireshark  # noqa: E402

PROTOS = os.path.join(STRESS_DIR, 'protos')
UNIT = 'fleet'
PORT_MAP = 'udp:5100=fleet.envelope.Envelope,tcp:5101=fleet.telemetry.Frame,udp:5102=fleet.status.Status'
ROOTS = {'fleet.envelope.Envelope': ('udp', 5100), 'fleet.telemetry.Frame': ('tcp', 5101),
         'fleet.status.Status': ('udp', 5102)}
HEURISTIC_PORT = 5199   # bare google.protobuf.Any of any other message
DECODE_AS_PORT = 5103   # plain fleet.cmd.Command, only with Decode As
DECODE_AS_MESSAGE = 'fleet.cmd.Command'
URL = 'type.googleapis.com/'
ANY_VALUE_MAX_SIZE = 512  # protos/google/protobuf/any.options


def step(text):
    print('\n== %s' % text)


# ---------------------------------------------------------------------------
# 1 + 2: generation
# ---------------------------------------------------------------------------

def generate(out, count, seed):
    step('gen-c: merge unit %s into one .c/.h' % UNIT)
    status, result, err = run_backend('gen-c', '--protos-root', PROTOS, '--unit', UNIT, '--out', out,
                                      '--with-runtime')
    if status:
        raise SystemExit(err)
    unit = result['units'][0]
    print('%s/%s.c, %s.h merged from %d generated files:' % (unit['dir'], UNIT, UNIT, len(unit['merged_from'])))
    print('  ' + ', '.join(unit['merged_from']))
    with open(os.path.join(out, UNIT, UNIT + '.h')) as handle:
        if 'pb_callback_t' in handle.read():
            raise SystemExit('pb_callback_t in fleet.h: a field is missing max_size/max_count')

    step('gen-data: %d sample(s) per message' % count)
    status, result, err = run_backend('gen-data', '--protos-root', PROTOS, '--unit', UNIT, '--out', out,
                                      '--seed', str(seed), '--count', str(count), '--formats', 'bin,c,hex')
    if status:
        raise SystemExit(err)
    if result['errors']:
        raise SystemExit('gen-data errors:\n  ' + '\n  '.join(result['errors']))
    samples = []
    for entry in result['units'][0]['messages']:
        ident = entry['files'][0][:-len('.bin')]
        with open(os.path.join(out, UNIT, 'data', ident + '.bin'), 'rb') as handle:
            samples.append((entry['message'], ident, handle.read()))
    print('%d samples of %d messages in %s' % (len(samples), len(set(s[0] for s in samples)),
                                               os.path.join(out, UNIT, 'data')))
    return samples


# ---------------------------------------------------------------------------
# 3: C round trip
# ---------------------------------------------------------------------------

def find_cc():
    candidates = []
    if os.environ.get('CC'):
        candidates.append(os.environ['CC'].split())
    for name in ('gcc', 'clang', 'cc'):
        if shutil.which(name):
            candidates.append([name])
    try:
        import ziglang  # noqa: F401  (pip install ziglang: bundles clang)
        candidates.append([sys.executable, '-m', 'ziglang', 'cc'])
    except ImportError:
        pass
    return candidates[0] if candidates else None


def roundtrip_source(samples, header_text):
    lines = ['/* Generated by stress_test.py: decode, validate and re-encode every sample. */',
             '#include <stdio.h>', '#include <string.h>', '#include <pb_encode.h>', '#include <pb_decode.h>',
             '#include "%s.h"' % UNIT]
    lines += ['#include "data/%s.h"' % ident for _, ident, _ in samples]
    lines += ['', 'static uint8_t out_buf[16384];', 'static pb_violations_t violations;', '']
    calls = []
    for msg, ident, _ in samples:
        ctype = nanopb_wireshark.c_identifier(msg.replace('.', '_'))
        size = ident.upper() + '_DATA_SIZE'
        lines += [
            'static int check_%s(void)' % ident,
            '{',
            '    static %s msg;' % ctype,
            '    pb_istream_t is = pb_istream_from_buffer(%s_data, %s);' % (ident, size),
            '    pb_ostream_t os = pb_ostream_from_buffer(out_buf, sizeof(out_buf));',
            '    memset(&msg, 0, sizeof(msg));',
            '    if (!pb_decode(&is, %s_fields, &msg)) {' % ctype,
            '        printf("FAIL %s: decode: %%s\\n", PB_GET_ERROR(&is));' % ident,
            '        return 1;',
            '    }',
            '    pb_violations_init(&violations);']
        # Messages without rules (and without sub-messages that have rules)
        # get no validator; only call the ones fleet.h declares.
        if re.search(r'\bpb_validate_%s\(' % ctype, header_text):
            lines += [
                '    if (!pb_validate_%s(&msg, &violations)) {' % ctype,
                '        printf("FAIL %s: validate: %%s %%s\\n", violations.violations[0].field_path,' % ident,
                '               violations.violations[0].constraint_id);',
                '        return 1;',
                '    }']
        lines += [
            '    if (!pb_encode(&os, %s_fields, &msg)) {' % ctype,
            '        printf("FAIL %s: encode: %%s\\n", PB_GET_ERROR(&os));' % ident,
            '        return 1;',
            '    }',
            '    if (os.bytes_written != %s || memcmp(out_buf, %s_data, %s) != 0) {' % (size, ident, size),
            '        /* nanopb always encodes repeated scalars packed (pb_encode.c), so',
            '         * unpacked input re-encodes differently: compare decoded content. */',
            '        static %s again;' % ctype,
            '        pb_istream_t is2 = pb_istream_from_buffer(out_buf, os.bytes_written);',
            '        memset(&again, 0, sizeof(again));',
            '        if (!pb_decode(&is2, %s_fields, &again) || memcmp(&again, &msg, sizeof(msg)) != 0) {' % ctype,
            '            printf("FAIL %s: re-encoded message differs\\n");' % ident,
            '            return 1;',
            '        }',
            '        printf("ok   %s (%%u bytes; re-encoded packed as %%u bytes, same content)\\n",' % ident,
            '               (unsigned)%s, (unsigned)os.bytes_written);' % size,
            '        return 0;',
            '    }',
            '    printf("ok   %s (%%u bytes, identical re-encode)\\n", (unsigned)%s);' % (ident, size),
            '    return 0;',
            '}',
            '']
        calls.append('    failed += check_%s();' % ident)
    lines += ['int main(void)', '{', '    int failed = 0;'] + calls
    lines += ['    printf("%%d of %d samples failed\\n", failed);' % len(samples), '    return failed != 0;',
              '}', '']
    return '\n'.join(lines)


def c_roundtrip(out, samples):
    step('C: compile merged unit (strict) and round-trip every sample')
    cc = find_cc()
    if not cc:
        print('SKIP: no C compiler (set CC, install gcc/clang, or pip install ziglang)')
        return None
    unit_dir = os.path.join(out, UNIT)
    src = os.path.join(unit_dir, 'stress_roundtrip.c')
    with open(os.path.join(unit_dir, UNIT + '.h')) as handle:
        header_text = handle.read()
    with open(src, 'w', newline='\n') as handle:
        handle.write(roundtrip_source(samples, header_text))
    strict = ['-std=c11', '-pedantic', '-Wall', '-Wextra', '-Werror', '-Wundef', '-Wconversion', '-Wcast-qual']
    for name in (UNIT + '.c', 'pb_common.c', 'pb_encode.c', 'pb_decode.c', 'pb_validate.c'):
        proc = subprocess.run(cc + strict + ['-I' + unit_dir, '-c', os.path.join(unit_dir, name),
                                             '-o', os.path.join(unit_dir, name + '.o')],
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
        print('%-16s %s' % (name, 'ok (strict C11)' if proc.returncode == 0 else 'FAILED'))
        if proc.returncode:
            print(proc.stdout)
            return False
    exe = os.path.join(unit_dir, 'stress_roundtrip' + ('.exe' if os.name == 'nt' else ''))
    objs = [os.path.join(unit_dir, n + '.o') for n in (UNIT + '.c', 'pb_common.c', 'pb_encode.c', 'pb_decode.c',
                                                       'pb_validate.c')]
    proc = subprocess.run(cc + ['-std=c11', '-Wall', '-Wextra', '-Werror', '-I' + unit_dir, '-o', exe, src] + objs,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    if proc.returncode:
        print(proc.stdout)
        return False
    proc = subprocess.run([exe], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    print(proc.stdout.rstrip())
    return proc.returncode == 0


