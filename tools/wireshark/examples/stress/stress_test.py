def showcase_cases(out):
    """Hand-made packets that combine every feature, with exact expectations."""

    from nanopb_data_generator import DataGenerator
    unit = nanopb_wireshark.Unit(PROTOS, UNIT, [])
    gen = nanopb_wireshark.unit_data_generator(unit, DataGenerator)

    def new(_type, **fields):
        msg = gen.registry.get_message_class(_type)()
        for key, value in fields.items():
            if isinstance(value, list):
                target = getattr(msg, key)
                for item in value:
                    target.add().CopyFrom(item) if hasattr(item, 'DESCRIPTOR') else target.append(item)
            elif hasattr(value, 'DESCRIPTOR'):
                getattr(msg, key).CopyFrom(value)
            else:
                setattr(msg, key, value)
        return msg

    def wrap(msg):
        return new('google.protobuf.Any', type_url=URL + msg.DESCRIPTOR.full_name, value=msg.SerializeToString())

    version = new('fleet.types.Version', major=2, minor=7, patch=1)
    imu = new('fleet.sensors.Imu', accel=new('fleet.types.Vec3', x=1.5, y=-2.0, z=9.75),
              gyro=new('fleet.types.Vec3', z=0.5), temp_c=-12, samples=[-1, 5, -300])
    battery = new('fleet.sensors.Battery', millivolts=3700, current_ma=-250, soc=87.5, charging=True, state=1,
                  cells=[new('shared.Quantity', value=3.7, unit=1), new('shared.Quantity', value=-0.25, unit=2)])
    gps = new('fleet.sensors.Gps', pos=new('fleet.types.GeoPoint', lat=32.08, lon=34.78, alt_cm=-150),
              fix_time_us=1700000000123456, satellites=9, snr=[30, 31, 40])
    frame = new('fleet.telemetry.Frame',
                device=new('fleet.types.DeviceId', hi=0x0102030405060708, lo=42, name='dev-alpha'),
                seq=7, ts=new('google.protobuf.Timestamp', seconds=1700000000, nanos=5),
                readings=[wrap(imu), wrap(battery), wrap(gps)],
                health=new('fleet.telemetry.Health', level=1,
                           faults=[new('fleet.telemetry.Health.Fault', code=17, detail='fan stalled')]),
                primary=wrap(new('fleet.sensors.Imu', temp_c=25)))
    frame.counters['rx'] = 42
    frame.counters['tx'] = -7

    env_frame = new('fleet.envelope.Envelope', version=version, frame=frame, severity=1,
                    signature=b'\xde\xad\xbe\xef')
    move = new('fleet.cmd.Command', id=9, priority=2, tags=['north', 'fast'],
               move=new('fleet.cmd.Move', target=new('fleet.types.GeoPoint', lat=-33.5, lon=151.25), speed_mps=2.5))
    env_cmd = new('fleet.envelope.Envelope', version=version, command=move)
    status = new('fleet.status.Status', code=1, history=[1, -2, 3], uptime_s=3600, offset_ns=-5)
    env_status = new('fleet.envelope.Envelope', version=version, status=status)
    inner_env = new('fleet.envelope.Envelope', version=version,
                    command=new('fleet.cmd.Command', id=1, stop=new('fleet.cmd.Stop', emergency=True)))
    deepest = new('fleet.envelope.Envelope', version=version, status=new('fleet.status.Status', code=2))
    inner_batch = new('fleet.envelope.Batch', items=[wrap(deepest)])
    env_batch = new('fleet.envelope.Envelope', version=version,
                    batch=new('fleet.envelope.Batch', items=[wrap(inner_env), wrap(inner_batch), wrap(gps)]))
    env_ext = new('fleet.envelope.Envelope', version=version,
                  extension=wrap(new('fleet.cmd.SetMode', mode=2)))
    plain_cmd = new('fleet.cmd.Command', id=77, raw=b'\x00\x01\x02', priority=3)

    udp = ROOTS['fleet.envelope.Envelope']
    return [
        Case('Envelope.frame: Frame with 3 Any readings, map, Timestamp, nested enums', udp[0], udp[1],
             env_frame.SerializeToString(),
             ['nanopb Protobuf: fleet.envelope.Envelope', 'major: 2', 'minor: 7',
              'frame (2): fleet.telemetry.Frame', 'name: dev-alpha', 'hi: 72623859790382856', 'lo: 42',
              'ts (3): google.protobuf.Timestamp', 'seconds: 1700000000', 'nanos: 5',
              'readings (4): google.protobuf.Any -> fleet.sensors.Imu',
              'readings (4): google.protobuf.Any -> fleet.sensors.Battery',
              'readings (4): google.protobuf.Any -> fleet.sensors.Gps',
              'x: 1.5', 'y: -2', 'z: 9.75', 'temp_c: -12', 'samples (4): packed [3]', 'samples: -300',
              'millivolts: 3700', 'current_ma: -250', 'soc: 87.5', 'charging: true',
              'state: STATE_CHARGING (1)', 'cells (6): shared.Quantity', 'value: 3.7', 'unit: UNIT_MILLIVOLT (1)',
              'value: -0.25', 'unit: UNIT_MILLIAMP (2)',
              'lat: 32.08', 'lon: 34.78', 'alt_cm: -150', 'fix_time_us: 1700000000123456', 'satellites: 9',
              'snr: 30', 'snr: 31', 'snr: 40',
              'counters (5): fleet.telemetry.Frame.CountersEntry', 'key: rx', 'value: 42', 'key: tx', 'value: -7',
              'health (6): fleet.telemetry.Health', 'level: LEVEL_DEGRADED (1)', 'code: 17', 'detail: fan stalled',
              'primary (7): google.protobuf.Any -> fleet.sensors.Imu', 'temp_c: 25',
              'severity: SEV_WARN (1)', 'signature: deadbeef'],
             filter='nanopb.fleet.sensors.Battery.state == 1 && nanopb.fleet.telemetry.Frame.CountersEntry.key == "rx"'),
        Case('Envelope.command: oneof Move, repeated strings, enum', udp[0], udp[1], env_cmd.SerializeToString(),
             ['command (3): fleet.cmd.Command', 'id: 9', 'move (2): fleet.cmd.Move', 'lat: -33.5', 'lon: 151.25',
              'speed_mps: 2.5', 'tags: north', 'tags: fast', 'priority: SEV_ERROR (2)'],
             filter='nanopb.fleet.cmd.Command.tags == "fast"'),
        Case('Envelope.status: proto2 Status (required, unpacked, sfixed64)', udp[0], udp[1],
             env_status.SerializeToString(),
             ['status (4): fleet.status.Status', 'code: CODE_BUSY (1)', 'history: 1', 'history: -2', 'history: 3',
              'uptime_s: 3600', 'offset_ns: -5'],
             filter='nanopb.fleet.status.Status.offset_ns == -5'),
        Case('Envelope.batch: Any recursion 4 levels deep', udp[0], udp[1], env_batch.SerializeToString(),
             ['batch (6): fleet.envelope.Batch', 'value: Any -> fleet.envelope.Envelope',
              'stop (3): fleet.cmd.Stop', 'emergency: true', 'value: Any -> fleet.envelope.Batch',
              'code: CODE_FAULT (2)', 'value: Any -> fleet.sensors.Gps', 'satellites: 9'],
             filter='nanopb.fleet.cmd.Stop.emergency == 1'),
        Case('Envelope.extension: Any oneof arm -> SetMode', udp[0], udp[1], env_ext.SerializeToString(),
             ['extension (5): google.protobuf.Any -> fleet.cmd.SetMode', 'mode: MODE_MANUAL (2)'],
             filter='nanopb.type_url == "type.googleapis.com/fleet.cmd.SetMode"'),
        Case('Frame directly on TCP', ROOTS['fleet.telemetry.Frame'][0], ROOTS['fleet.telemetry.Frame'][1],
             frame.SerializeToString(),
             ['nanopb Protobuf: fleet.telemetry.Frame', 'name: dev-alpha', 'value: Any -> fleet.sensors.Battery'],
             filter='nanopb.fleet.telemetry.Frame.seq == 7'),
        Case('Status directly (proto2 default text not on the wire)', ROOTS['fleet.status.Status'][0],
             ROOTS['fleet.status.Status'][1], status.SerializeToString(),
             ['nanopb Protobuf: fleet.status.Status', 'code: CODE_BUSY (1)'],
             filter='nanopb.fleet.status.Status.uptime_s == 3600'),
        Case('Bare Any(Battery) on an unmapped port (heuristic)', 'udp', HEURISTIC_PORT,
             wrap(battery).SerializeToString(),
             ['nanopb Protobuf: google.protobuf.Any', 'value: Any -> fleet.sensors.Battery', 'soc: 87.5'],
             filter='nanopb.fleet.sensors.Battery.millivolts == 3700', how='heuristic'),
        Case('Plain Command on port %d (Decode As)' % DECODE_AS_PORT, 'udp', DECODE_AS_PORT,
             plain_cmd.SerializeToString(),
             ['nanopb Protobuf: fleet.cmd.Command', 'id: 77', 'raw: 000102', 'priority: SEV_FATAL (3)'],
             filter='nanopb.fleet.cmd.Command.id == 77', how='decode_as'),
        Case('Malformed Envelope (truncated nested Frame)', udp[0], udp[1], env_frame.SerializeToString()[:40],
             ['nanopb Protobuf: fleet.envelope.Envelope'], experts=['Length exceeds message'],
             filter='nanopb.malformed', verdict='dropped'),
    ]


def sample_cases(samples):
    """Every generated sample as a packet: roots on their port, others as Any."""

    cases = []
    for msg, ident, data in samples:
        if msg in ROOTS:
            transport, port = ROOTS[msg]
            cases.append(Case('sample %s' % ident, transport, port, data,
                              ['nanopb Protobuf: %s' % msg], filter='nanopb.message == "%s"' % msg))
        else:
            url = (URL + msg).encode()
            payload = b'\x0a' + varint(len(url)) + url + b'\x12' + varint(len(data)) + data
            # The project's any.options gives Any.value 512 bytes: a nanopb
            # receiver cannot decode a bigger payload, so it is dropped.
            too_big = len(data) > ANY_VALUE_MAX_SIZE
            cases.append(Case('sample %s (as Any)' % ident, 'udp', HEURISTIC_PORT, payload,
                              ['value: Any -> %s' % msg], filter='nanopb.message == "%s"' % msg, how='heuristic',
                              experts=['value: nanopb.max_size'] if too_big else (),
                              verdict='dropped' if too_big else 'passed'))
    return cases


# ---------------------------------------------------------------------------
# 5 + 6: tshark, install
# ---------------------------------------------------------------------------

def run_tshark(pcap, cases, installed):
    step('tshark: dissect %d packets (%s dissector)' % (len(cases), 'installed' if installed else 'repo'))
    if not live_test.find_tshark():
        print('SKIP: tshark not found')
        return None
    results = live_test.verify(pcap, cases, isolated=not installed, port_map=PORT_MAP, protos_root=PROTOS,
                               decode_as_port=DECODE_AS_PORT, decode_as_message=DECODE_AS_MESSAGE)
    failed = 0
    for number, case, problems in results:
        if problems or number <= 10:
            print('%-4s %3d  %s' % ('FAIL' if problems else 'PASS', number, case.name))
        for problem in problems:
            print('           ' + problem)
        failed += bool(problems)
    print('%d/%d packets passed' % (len(results) - failed, len(results)))
    return failed == 0


def install(out):
    step('install stress schema into your Wireshark')
    plugins = nanopb_wireshark.default_plugins_dir()
    status, result, err = run_backend('install-studio', '--plugins-dir', plugins)
    if status:
        raise SystemExit(err)
    status, result, err = run_backend('install-dissector', '--protos-root', PROTOS, '--plugins-dir', plugins,
                                      '--port-map', PORT_MAP)
    if status:
        raise SystemExit(err)
    config = os.path.join(plugins, 'nanopb', 'studio_config.luadata')
    lua = nanopb_wireshark.lua_str
    with open(config, 'w', newline='\n') as handle:
        handle.write('-- written by tools/wireshark/examples/stress/stress_test.py --install\nreturn {\n')
        for key, value in (('python', sys.executable), ('nanopb_root', REPO_ROOT), ('protos_root', PROTOS),
                           ('output_dir', out), ('extra_includes', ''), ('port_map', PORT_MAP)):
            handle.write('  %s = %s,\n' % (key, lua(value)))
        handle.write('}\n')
    for path in result['files'] + [config]:
        print('installed %s' % path)
    print('Wireshark: Analyze > Reload Lua Plugins (Ctrl+Shift+L). '
          'Restore the small test schema with: live_test.py setup --reset-config')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--out', default=os.path.abspath('nanopb_stress_out'))
    parser.add_argument('--count', type=int, default=3, help='samples per message')
    parser.add_argument('--seed', type=int, default=1)
    parser.add_argument('--install', action='store_true',
                        help='install the stress schema + port map into your Wireshark and verify with it')
    args = parser.parse_args(argv)
    out = os.path.abspath(args.out)
    if os.path.isdir(os.path.join(out, UNIT)):
        shutil.rmtree(os.path.join(out, UNIT))

    samples = generate(out, args.count, args.seed)
    c_ok = c_roundtrip(out, samples)

    step('packets')
    cases = showcase_cases(out) + sample_cases(samples)
    pcap = os.path.join(out, 'stress.pcap')
    live_test.write_pcap(pcap, cases)
    with open(os.path.join(out, 'stress_packets.txt'), 'w', newline='\n') as handle:
        for i, case in enumerate(cases, 1):
            handle.write('%3d  %s/%-5d %-10s %s\n' % (i, case.transport, case.port, case.how, case.name))
            for line in case.expect + ['expert: ' + e for e in case.experts]:
                handle.write('          %s\n' % line)
            if case.filter:
                handle.write('          filter: %s\n' % case.filter)
    print('%s: %d packets (list: stress_packets.txt)' % (pcap, len(cases)))
    print('ports: %s; heuristic Any on udp/%d; Decode As udp/%d -> %s'
          % (PORT_MAP, HEURISTIC_PORT, DECODE_AS_PORT, DECODE_AS_MESSAGE))

    if args.install:
        install(out)
    t_ok = run_tshark(pcap, cases, installed=args.install)

    step('summary')
    for name, ok in (('C compile + round trip', c_ok), ('tshark dissection', t_ok)):
        print('%-24s %s' % (name, {True: 'PASS', False: 'FAIL', None: 'SKIPPED'}[ok]))
    return 1 if False in (c_ok, t_ok) else 0


if __name__ == '__main__':
    sys.exit(main())
